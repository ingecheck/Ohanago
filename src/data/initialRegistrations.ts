import { RunnerRegistration } from '../types/race';

export const getStoredRegistrations = (): RunnerRegistration[] => {
  try {
    const saved = localStorage.getItem('ohana_registrations');
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed) && parsed.length >= INITIAL_REGISTRATIONS.length) {
        return parsed;
      }
    }
  } catch (e) {}
  return INITIAL_REGISTRATIONS;
};

export const saveRegistrations = (registrations: RunnerRegistration[]): void => {
  try {
    localStorage.setItem('ohana_registrations', JSON.stringify(registrations));
    fetch('/api/registrations', {
      method: 'PUT',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ registrations }),
    }).catch(() => {});
  } catch (e) {}
};

export const addRegistration = async (registration: Omit<RunnerRegistration, 'id' | 'registrationNumber' | 'createdAt'>): Promise<RunnerRegistration> => {
  const current = getStoredRegistrations();
  const nextNum = current.length > 0
    ? Math.max(...current.map((r) => r.registrationNumber || r.bibNumber || 0)) + 1
    : 1;
  const newRecord: RunnerRegistration = {
    ...registration,
    id: `OHA-2026-${String(nextNum).padStart(4, '0')}`,
    registrationNumber: nextNum,
    bibNumber: nextNum,
    createdAt: new Date().toISOString(),
  };

  const updated = [newRecord, ...current];
  saveRegistrations(updated);

  try {
    const res = await fetch('/api/registrations', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(newRecord),
    });
    if (res.ok) {
      const serverSaved = await res.json();
      return serverSaved;
    }
  } catch (e) {}

  return newRecord;
};

export const exportToCSV = (registrations: RunnerRegistration[]) => {
  const headers = [
    'N°',
    'Código Registro',
    'Nombres',
    'Apellidos',
    'Documento',
    'Número Doc',
    'Modalidad',
    'Celular',
    'Ciudad',
    'Estado Pago',
    'Check-in Largada',
    'Hora Check-in'
  ];

  const rows = registrations.map(r => [
    r.registrationNumber || r.bibNumber || '',
    r.id || `OHA-2026-${String(r.registrationNumber).padStart(4, '0')}`,
    `"${r.firstName}"`,
    `"${r.lastName}"`,
    r.documentType,
    r.documentNumber,
    r.modality || 'Presencial',
    r.whatsapp,
    r.city,
    r.paymentStatus,
    r.confirmedAtStart ? 'SÍ' : 'NO',
    r.startCheckinTime ? new Date(r.startCheckinTime).toLocaleTimeString() : ''
  ]);

  const csvContent = [headers.join(','), ...rows.map(row => row.join(','))].join('\n');
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.setAttribute('href', url);
  link.setAttribute('download', `participantes_ohana_go_5k_${new Date().toISOString().slice(0, 10)}.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
};

